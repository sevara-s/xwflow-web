export function statusLabel(code: string): string {
  const entry = catalog.status[code as keyof typeof catalog.status];
  return entry ? entry.label : code;
}

export function statusBadgeTones(): Record<string, string> {
  const tones: Record<string, string> = {};
  for (const entry of Object.values(catalog.status)) {
    tones[entry.label] = entry.tone;
  }
  return tones;
}
